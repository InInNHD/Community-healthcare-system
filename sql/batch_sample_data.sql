-- 更新库存总量为各批次剩余量之和
UPDATE `medicine_info` SET `medicine_stock` = (
    SELECT COALESCE(SUM(`remaining_quantity`), 0)
    FROM `medicine_batch`
    WHERE `medicine_batch`.`medicine_id` = `medicine_info`.`id`
      AND `medicine_batch`.`status` = 1
);

-- 设置低库存预警阈值
UPDATE `medicine_info` SET `medicine_stock_min` = CASE
    WHEN `medicine_stock` <= 20 THEN 5
    WHEN `medicine_stock` <= 100 THEN 20
    ELSE 50
END;
